//! The system clipboard, used to paste text and restore what was there.
//!
//! The paste flow (`docs/ENGINEERING.md`, M4.1): read the user's text,
//! [`write_dictation`](Clipboard::write_dictation) the transcript (privacy
//! markers plus our [`SessionMarker`]), paste, then
//! [`restore_if_unchanged`](Clipboard::restore_if_unchanged) so the user's
//! text comes back only if nothing replaced ours in the meantime.

use thiserror::Error;

/// Why a [`Clipboard`] call failed.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum ClipboardError {
    /// The clipboard couldn't be opened (another app holds it, on Windows).
    #[error("clipboard is unavailable: {0}")]
    Unavailable(String),
}

/// The privacy markers on clipboard contents. On macOS they are the
/// `org.nspasteboard` types clipboard managers honour; Windows has the
/// equivalent `ExcludeClipboardContentFromMonitorProcessing` format.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct ClipboardMarkers {
    /// `org.nspasteboard.TransientType`: don't keep it in history.
    pub transient: bool,
    /// `org.nspasteboard.ConcealedType`: don't show it.
    pub concealed: bool,
    /// `org.nspasteboard.AutoGeneratedType`: an app wrote it, not the user.
    pub auto_generated: bool,
}

impl ClipboardMarkers {
    /// No markers: what the user's own copies and restored text carry.
    pub const NONE: Self = Self {
        transient: false,
        concealed: false,
        auto_generated: false,
    };

    /// All three: what every dictation write carries.
    pub const DICTATION: Self = Self {
        transient: true,
        concealed: true,
        auto_generated: true,
    };
}

/// Identifies one dictation write, so a restore can tell whether the
/// clipboard still holds it. Implementations make a new one per write (a
/// private pasteboard type holding a random token, plus the change count).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct SessionMarker(String);

impl SessionMarker {
    /// Wraps an implementation's token.
    #[must_use]
    pub fn new(token: impl Into<String>) -> Self {
        Self(token.into())
    }

    /// The token.
    #[must_use]
    pub fn token(&self) -> &str {
        &self.0
    }
}

/// Plain-text access to the system clipboard.
///
/// Threading: `&self` methods, callable from any thread. Real
/// implementations may block briefly (Windows retries `OpenClipboard`), so
/// the pipeline calls them from a blocking task, not the async executor.
pub trait Clipboard: Send + Sync {
    /// The clipboard's text, or `None` if it holds no text (empty, or an
    /// image or files).
    ///
    /// # Errors
    ///
    /// [`ClipboardError::Unavailable`] if the clipboard can't be read.
    ///
    /// Threading: may block briefly; call from a blocking task.
    fn read_text(&self) -> Result<Option<String>, ClipboardError>;

    /// Replaces the clipboard's contents with `text`, with no markers, as if
    /// the user had copied it. Dictation uses
    /// [`write_dictation`](Self::write_dictation) and
    /// [`restore_if_unchanged`](Self::restore_if_unchanged) instead.
    ///
    /// # Errors
    ///
    /// [`ClipboardError::Unavailable`] if the clipboard can't be written;
    /// its previous contents are then unchanged.
    ///
    /// Threading: may block briefly; call from a blocking task.
    fn write_text(&self, text: &str) -> Result<(), ClipboardError>;

    /// Replaces the clipboard's contents with dictated `text`, marked with
    /// [`ClipboardMarkers::DICTATION`] (so clipboard managers skip it) and
    /// a new [`SessionMarker`], which it returns.
    ///
    /// # Errors
    ///
    /// [`ClipboardError::Unavailable`] if the clipboard can't be written;
    /// its previous contents are then unchanged.
    ///
    /// Threading: may block briefly; call from a blocking task.
    fn write_dictation(&self, text: &str) -> Result<SessionMarker, ClipboardError>;

    /// If the clipboard still holds the write that returned `session`,
    /// replaces it with `previous` (or clears it, for `None`) with no
    /// markers, and returns `true`. If anything else is on the clipboard
    /// (the user copied something, even the same text), leaves it alone
    /// and returns `false`.
    ///
    /// # Errors
    ///
    /// [`ClipboardError::Unavailable`] if the clipboard can't be read or
    /// written; it is then unchanged.
    ///
    /// Threading: may block briefly; call from a blocking task.
    fn restore_if_unchanged(
        &self,
        session: &SessionMarker,
        previous: Option<&str>,
    ) -> Result<bool, ClipboardError>;
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn marker_presets() {
        assert_eq!(ClipboardMarkers::default(), ClipboardMarkers::NONE);
        let all = ClipboardMarkers::DICTATION;
        assert!(all.transient && all.concealed && all.auto_generated);
    }

    #[test]
    fn session_marker_keeps_its_token() {
        assert_eq!(SessionMarker::new("abc").token(), "abc");
    }
}
