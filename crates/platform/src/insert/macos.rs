//! The macOS paste adapters: [`MacPasteboard`] (`NSPasteboard`) and
//! [`MacPasteKeys`] (⌘ plus the layout's V key through `CGEventPost`).
//!
//! The layout lookup (`UCKeyTranslate` over the current keyboard layout) is
//! adapted from Handy's `src-tauri/src/input.rs` (MIT, commit 9e57a0d; see
//! `NOTICE`), with the "scan for the key that types v with ⌘" idea it
//! shares with Muesli's `PasteShortcut.swift` (MIT).

