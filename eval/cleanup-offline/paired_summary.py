"""Summarise the paired Nemotron raw -> OpenRouter GPT-6.2-sol v4 cleanup run under both judges.

    python3 eval/cleanup-offline/paired_summary.py [paired-results/nemotron_sol_v4]

Reads, per judge, the raw Nemotron verdicts (raw_codex.csv, raw_claude.csv) and the pasted-text
verdicts (scored_codex.csv, scored.csv), all on the same 151 clips. Prints ZER / AMEND for raw and
cleaned on tune / check / all (fixed speaker split eval/groq-cleanup/split.csv), fixed / regressed
counts (transitions to and from zero edits), and rewrites changes.md with every clip either judge
counts as fixed or regressed, plus clips whose edit count rose without crossing zero.
"""
import csv
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
RUN = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "paired-results" / "nemotron_sol_v4"
SPLIT = {r["clip_id"]: r["half"] for r in csv.DictReader(open(HERE.parent / "groq-cleanup" / "split.csv", newline=""))}
JUDGES = {"GPT-6 Astra": ("raw_codex.csv", "scored_codex.csv"), "Claude Opus 5.5": ("raw_claude.csv", "scored.csv")}


def read(p):
    with open(p, newline="", encoding="utf-8") as f:
        return {r["clip_id"]: r for r in csv.DictReader(f) if r.get("edits", "") != ""}


def zer_amend(rows):
    z = 100 * sum(int(r["edits"]) == 0 for r in rows) / len(rows)
    return z, 100 * sum(int(r["edits"]) for r in rows) / sum(int(r["chars"]) for r in rows)


def main():
    print("| Judge | Paired clips | Raw ZER % | Cleaned ZER % | Fixed / regressed | Raw / cleaned AMEND % |")
    print("| --- | ---: | ---: | ---: | ---: | ---: |")
    changes = []
    for judge, (rf, cf) in JUDGES.items():
        raw, clean = read(RUN / rf), read(RUN / cf)
        ids = sorted(raw.keys() & clean.keys())
        for half in ("all", "tune", "check"):
            sel = [c for c in ids if half == "all" or SPLIT[c] == half]
            rz, ra = zer_amend([raw[c] for c in sel])
            cz, ca = zer_amend([clean[c] for c in sel])
            fixed = sum(int(raw[c]["edits"]) > 0 and int(clean[c]["edits"]) == 0 for c in sel)
            broke = sum(int(raw[c]["edits"]) == 0 and int(clean[c]["edits"]) > 0 for c in sel)
            print(f"| {judge}, {half} | {len(sel)} | {rz:.1f} | {cz:.1f} | {fixed} / {broke} | {ra:.2f} / {ca:.2f} |")
        for c in ids:
            re_, ce = int(raw[c]["edits"]), int(clean[c]["edits"])
            kind = ("Fixed" if re_ > 0 and ce == 0 else "Regressed" if re_ == 0 and ce > 0
                    else f"Worse ({re_} -> {ce} edits)" if ce > re_ else None)
            if kind:
                changes.append((c, kind, judge, raw[c]["draft"], clean[c]["draft"]))
    with open(RUN / "changes.md", "w", encoding="utf-8") as f:
        f.write("# Nemotron raw -> OpenRouter GPT-6.2-sol v4 (guarded): clips that changed status\n\n"
                "Fixed = raw had edits, pasted text has none; Regressed = the reverse; Worse = more edits "
                "without crossing zero. Generated by paired_summary.py.\n")
        for c, kind, judge, raw_d, clean_d in sorted(changes):
            f.write(f"\n### {c} · {kind} · {judge}\n\n- Raw: {raw_d}\n- Pasted: {clean_d}\n")
    print(f"\nwrote {RUN / 'changes.md'} ({len(changes)} entries)")


if __name__ == "__main__":
    main()
